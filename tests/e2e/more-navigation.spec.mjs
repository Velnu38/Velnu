import { test, expect } from '@playwright/test'
import { mock, B, business } from './audit-fixture.mjs'

const setupLinks = ['Company Profile', 'Team & Access', 'Email & Text Setup', 'Invoice & Estimate Setup', 'Calendar Connections', 'Working Hours & Team Availability']
const moreButton = page => page.locator(page.viewportSize().width > 900 ? '.sidebar' : '.mobile-nav').getByRole('button', {name: 'More', exact: true})
const more = page => page.getByRole('dialog', {name: 'More navigation'})

for (const width of [320, 390, 1440]) test(`More consolidates setup and preserves related workspaces at ${width}px`, async ({page}) => {
  await page.setViewportSize({width, height: 900})
  const state = await mock(page, {ai: true})
  await page.goto('/')
  const origin = await page.evaluate(() => performance.timeOrigin)
  await moreButton(page).click()
  for (const label of [...setupLinks, 'Help & Support', 'Subscription']) await expect(more(page).getByRole('link', {name: new RegExp('^' + label.replaceAll('&', '\\&'))})).toBeVisible()
  for (const label of ['Reminders', 'Payments', 'Financial performance', 'Settings', 'Type to Fin']) await expect(more(page).getByRole('link', {name: label, exact: true})).toHaveCount(0)
  await expect(more(page).getByRole('button', {name: 'Ask Fin', exact: true})).toHaveCount(0)
  await more(page).getByRole('link', {name: /^Company Profile/}).click()
  await expect(page.getByRole('heading', {name: 'Company Profile', exact: true})).toBeVisible()
  await expect(page.getByLabel('Company name', {exact: true})).toBeVisible()
  await moreButton(page).click()
  await more(page).getByRole('link', {name: /^Invoice & Estimate Setup/}).click()
  await expect(page.getByRole('heading', {name: 'Invoice & Estimate Setup', exact: true})).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', {name: 'Company Profile', exact: true})).toBeVisible()
  await moreButton(page).click()
  await more(page).getByRole('link', {name: /^Schedule/}).click()
  await page.getByRole('link', {name: 'Manage Reminders', exact: true}).click()
  await expect(page).toHaveURL(/view=reminders/)
  await page.goBack()
  await expect(page.getByRole('link', {name: 'Manage Reminders', exact: true})).toBeVisible()
  await page.locator(width > 900 ? '.sidebar' : '.mobile-nav').getByRole('button', {name: 'Home', exact: true}).click()
  await page.getByRole('button',{name:/^View all income & expenses/}).click()
  await page.getByRole('link', {name: 'Payment history', exact: true}).click()
  await expect(page).toHaveURL(/view=payments/)
  expect(await page.evaluate(() => performance.timeOrigin)).toBe(origin)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(state.calls.some(call => call.path.includes('/send-'))).toBe(false)
})

test('More navigation protects unsaved company edits', async ({page}) => {
  await mock(page)
  await page.goto('/?view=settings&section=company')
  await page.getByLabel('Company name', {exact: true}).fill('Keep these edits')
  await moreButton(page).click()
  page.once('dialog', dialog => dialog.dismiss())
  await more(page).getByRole('link', {name: /^Invoice & Estimate Setup/}).click()
  await more(page).getByRole('button', {name: 'Close', exact: true}).click()
  await expect(page.getByLabel('Company name', {exact: true})).toHaveValue('Keep these edits')
  await expect(page).toHaveURL(/section=company/)
})

test('restricted member cannot reach owner setup through More or a saved link', async ({page}) => {
  await mock(page, {owner: false, ai: true})
  await page.route('**/rest/v1/business_members?**', route => route.fulfill({json: {business_id: B, role: 'viewer', access_modules: ['calendar'], businesses: business}}))
  await page.goto('/')
  await moreButton(page).click()
  await expect(more(page).getByRole('link', {name: /^Calendar Connections/})).toBeVisible()
  for (const label of setupLinks.filter(label => label !== 'Calendar Connections')) await expect(more(page).getByRole('link', {name: new RegExp('^' + label)})).toHaveCount(0)
  await page.goto('/?view=settings&section=documents')
  await expect(page.getByRole('alert')).toContainText('not included in your access')
  await expect(page.getByRole('button', {name: 'Save document setup'})).toHaveCount(0)
})
