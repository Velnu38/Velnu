import {test,expect} from '@playwright/test'
import {DateTime} from 'luxon'
import {mock,C} from './audit-fixture.mjs'
for(const kind of ['invoice','estimate'])test(`${kind}: preview does not save; back preserves work and date; save writes once`,async({page})=>{
 const state=await mock(page)
 await page.goto('/?view='+kind+'s')
 await page.getByRole('button',{name:'Create '+kind,exact:true}).click()
 const form=page.getByRole('dialog',{name:'Create an '+kind,exact:true})
 const issued=await form.getByLabel('Issue date',{exact:true}).inputValue()
 await expect(form.getByLabel(kind==='invoice'?'Due date':'Valid until',{exact:true})).toHaveValue(DateTime.fromISO(issued).plus({days:kind==='estimate'?30:0}).toISODate())
 await form.getByRole('combobox',{name:'Customer',exact:true}).fill('Test')
 await form.getByRole('option',{name:/Test Customer/}).click()
 await form.getByLabel('Line 1 description',{exact:true}).fill('Lawn maintenance')
 await form.getByLabel('Line 1 unit price',{exact:true}).fill('250')
 const ending=DateTime.fromISO(issued).plus({days:45}).toISODate()
 await form.getByLabel(kind==='invoice'?'Due date':'Valid until',{exact:true}).fill(ending)
 await form.getByRole('button',{name:'Preview',exact:true}).click()
 await expect(form.locator('.document-paper')).toContainText('Lawn maintenance')
 await expect(form.locator('.document-paper')).toContainText('$250.00')
 await expect(form.locator('footer.document-footer')).toHaveText('Thank You!')
 await expect(form.locator('footer.document-footer')).toHaveCSS('text-align','center')
 for (const width of [390,1280]) {
  await page.setViewportSize({width,height:1000})
  const bounds=await form.locator('.document-paper').boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x+bounds.width).toBeLessThanOrEqual(width+1)
  await expect(form.locator('footer.document-footer')).toBeVisible()
 }

 await expect(form.getByRole('button',{name:'Send Text',exact:true})).toBeDisabled()
 expect(state.documents).toHaveLength(0)
 await form.getByRole('button',{name:'← Back to edit',exact:true}).click()
 await expect(form.getByLabel('Line 1 description',{exact:true})).toHaveValue('Lawn maintenance')
 await expect(form.getByLabel(kind==='invoice'?'Due date':'Valid until',{exact:true})).toHaveValue(ending)
 await form.getByRole('button',{name:'Preview',exact:true}).click()
 await form.getByRole('button',{name:'Save Draft',exact:true}).click()
 await expect.poll(()=>state.documents.length).toBe(1)
 expect(state.documents[0].payload[kind==='invoice'?'due_date':'expires_on']).toBe(ending)
 expect(state.calls.some(call=>call.path.includes('/send-'))).toBe(false)
})

for (const kind of ['invoice', 'estimate']) test(`${kind}: entry fields are visible, tax is inherited, and tax exceptions survive preview`, async ({ page }) => {
 const state = await mock(page, { defaultTax: 5 })
 await page.setViewportSize({ width: 390, height: 844 })
 await page.goto('/?view=' + kind + 's')
 await page.getByRole('button', { name: 'Create ' + kind, exact: true }).click()
 const form = page.getByRole('dialog', { name: 'Create an ' + kind, exact: true })
 const customer = form.getByRole('combobox', { name: 'Customer', exact: true })
 await expect(customer).toBeVisible()
 await expect(form.getByLabel('Line 1 description', { exact: true })).toBeVisible()
 await expect(form.getByLabel('Line 1 Tax rate (%)', { exact: true })).toBeHidden()
 expect(await form.locator('.line-item').first().locator('input').evaluateAll(inputs => inputs.map(input => input.placeholder))).toEqual(['Description', 'Unit price', 'Qty'])
 await customer.fill('Test')
 await form.getByRole('option', { name: /Test Customer/ }).click()
 await form.getByLabel('Line 1 description', { exact: true }).fill('Tax-exempt labor')
 await form.getByLabel('Line 1 unit price', { exact: true }).fill('100')
 await expect(form.getByLabel('Line 1 quantity', { exact: true })).toHaveValue('1')
 await form.getByText('Tax options · 5% default', { exact: true }).click()
 await form.getByLabel('Line 1 Tax rate (%)', { exact: true }).fill('0')
 await form.getByRole('button', { name: 'Preview', exact: true }).click()
 const paper = form.locator('.document-paper')
 await expect(paper.getByText('Tax', { exact: true })).toHaveCount(0)
 await form.getByRole('button', { name: '← Back to edit', exact: true }).click()
 await form.getByRole('button', { name: '+ Add line', exact: true }).click()
 await form.getByLabel('Line 2 description', { exact: true }).fill('Taxable supplies')
 await form.getByLabel('Line 2 unit price', { exact: true }).fill('100')
 await form.getByRole('button', { name: 'Preview', exact: true }).click()
 await expect(paper.getByText('$205.00', { exact: true })).toBeVisible()
 await form.getByRole('button', { name: 'Save Draft', exact: true }).click()
 await expect.poll(() => state.documents.length).toBe(1)
 expect(state.documents[0].payload.items.map(item => item.tax_rate)).toEqual([0, 5])
})
