import {test,expect} from '@playwright/test'
import {mock,C} from './audit-fixture.mjs'
import {openFinTyping} from './navigation.mjs'
const duplicate={id:'88888888-8888-4888-8888-888888888888',first_name:'Test',last_name:'Customer',company:'Electrical',email:'other@example.test',phone:'(757) 555-1234'}
test('job customer requires a selection, supports keyboard and clears stale links on editing',async({page})=>{
 const state=await mock(page);state.customers.push(duplicate)
 await page.goto('/?view=work&new=1')
 const input=page.getByRole('combobox',{name:'Customer',exact:true})
 await input.fill('Test')
 await expect(page.getByRole('listbox',{name:'Matching saved customers'}).getByRole('option')).toHaveCount(2)
 expect(await input.evaluate(el=>el.checkValidity())).toBe(false)
 await input.fill('757555');await input.press('ArrowDown');await input.press('Enter')
 await expect(input).toHaveValue('Test Customer')
 await expect(page.locator('.customer-picker-selected')).toContainText('other@example.test')
 expect(await input.evaluate(el=>el.checkValidity())).toBe(true)
 await input.fill('Nobody')
 expect(await input.evaluate(el=>el.checkValidity())).toBe(false)
 await expect(page.getByText(/No saved customer matches/)).toBeVisible()
})
test('Fin suggests duplicate names with contact details and opens the invoice editor with the chosen record',async({page})=>{
 const state=await mock(page,{ai:true});state.customers.push(duplicate)
 await page.goto('/');await openFinTyping(page)
 const request=page.getByRole('textbox',{name:'Describe your invoice or request'})
 await request.fill('Create an invoice for Test Customer for mowing $100')
 const suggestions=page.getByRole('region',{name:'Suggested customers for Fin'})
 await expect(suggestions.getByRole('button')).toHaveCount(2)
 await suggestions.getByRole('button').filter({hasText:'other@example.test'}).click()
 const editor=page.getByRole('dialog',{name:'Create an invoice'})
 await expect(page).toHaveURL(/view=invoices/)
 await expect(editor.getByRole('combobox',{name:'Customer',exact:true})).toHaveValue('Test Customer')
 await expect(editor.locator('.customer-picker-selected')).toContainText('other@example.test')
 await expect(editor.getByLabel('Line 1 unit price',{exact:true})).toHaveValue('100')
 await expect(request).toHaveCount(0)
 expect(state.documents).toHaveLength(0)
})
test('invoice creation requires explicit new customer choice',async({page})=>{
 const state=await mock(page)
 await page.goto('/?view=invoices&new=1')
 const input=page.getByRole('combobox',{name:'Customer',exact:true})
 await input.fill('Unknown Client')
 expect(await input.evaluate(el=>el.checkValidity())).toBe(false)
 await page.getByRole('button',{name:'Create a new customer',exact:true}).click()
 await expect(page.getByLabel('Customer name',{exact:true})).toHaveValue('Unknown Client')
 expect(state.documents).toHaveLength(0)
})
