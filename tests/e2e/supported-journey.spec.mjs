import {test,expect} from '@playwright/test'
import {mkdir} from 'node:fs/promises'
import {openJobSection} from './job-workspace-navigation.mjs'
const job='44444444-4444-4444-8444-444444444444'
for(const width of [320,390])for(const stage of ['paid','pending'])test(`supported journey ${stage} at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:844})
 await page.goto(`/tests/operations/preview.html?screen=jobs&scenario=journey&journeyStage=${stage}&job=${job}&layout=phone`)
 const workspace=page.getByRole('region',{name:'Selected job workspace',exact:true})
 await expect(workspace).toBeVisible()
 await expect(workspace.locator('.jm-phone-status')).toHaveText(stage==='paid'?'Closed · Paid':'Payment pending')
 await expect(workspace.locator('.jm-next-action').getByRole('link')).toHaveText(stage==='paid'?'View payment history':'View payment status')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await mkdir('tmp/journey-review',{recursive:true})
 if(width===390)await page.screenshot({path:`tmp/journey-review/${stage}-phone.png`,fullPage:true})
 await openJobSection(page,'Activity history')
 await expect(workspace.getByLabel('Workflow activity', {exact:true})).toContainText('Issued invoice link opened')
 await expect(workspace.getByLabel('Workflow activity', {exact:true})).toContainText('security scanner')
 await expect(workspace.getByLabel('Workflow activity', {exact:true}).getByRole('button',{name:'Refresh activity',exact:true})).toHaveCount(1)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 if(width===390&&stage==='paid')await page.screenshot({path:'tmp/journey-review/activity-phone.png',fullPage:true})
})
for(const width of [320,390])test(`notification controls and reviewed change at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:844})
 await page.goto('/tests/operations/preview.html?screen=journey-settings&layout=phone')
 const confirmations=page.getByRole('checkbox',{name:'Email the customer when an appointment is confirmed'})
 await expect(confirmations).not.toBeChecked();await expect(page.getByRole('checkbox',{name:'Email a receipt after a payment is recorded'})).not.toBeChecked()
 await confirmations.check();await page.getByRole('button',{name:'Save customer notifications',exact:true}).click();await expect(page.getByText('Saved confirmations: Enabled.',{exact:false})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 if(width===390)await page.screenshot({path:'tmp/journey-review/notification-settings-phone.png',fullPage:true})
 await page.goto(`/tests/operations/preview.html?screen=jobs&scenario=journey-notice&job=${job}&section=activity&layout=phone`)
 await page.getByRole('button',{name:'Review customer notice',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Review customer notice',exact:true})
 await expect(dialog).toContainText('customer@example.test');await expect(dialog).toContainText('Your new appointment')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 if(width===390)await page.screenshot({path:'tmp/journey-review/notice-review-phone.png',fullPage:true})
 await dialog.getByRole('button',{name:'Send Finviant Email',exact:true}).click();await expect(dialog).toContainText('Queued');await expect(dialog.getByRole('button',{name:'Send Finviant Email',exact:true})).toHaveCount(0)
 expect(await page.evaluate(()=>window.__journeyNoticeSends)).toBe(1)
 await dialog.getByRole('button',{name:'Close',exact:true}).click();await expect(page.getByLabel('Workflow activity',{exact:true})).toContainText('Customer email: Queued')
})
test('a conflicting notification save preserves the owner choices and does not claim the rule is enabled',async({page})=>{
 await page.goto('/tests/operations/preview.html?screen=journey-settings&scenario=policy-conflict&layout=phone')
 const confirmations=page.getByRole('checkbox',{name:'Email the customer when an appointment is confirmed'})
 await confirmations.check();await page.getByRole('button',{name:'Save customer notifications',exact:true}).click();await expect(page.getByRole('alert')).toContainText('could not be saved');await expect(confirmations).toBeChecked();await expect(page.getByText('Saved confirmations: Off.',{exact:false})).toBeVisible()
})
