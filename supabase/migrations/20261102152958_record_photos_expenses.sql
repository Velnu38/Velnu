-- Photos are private workspace records, never public invoice/approval assets.
create table public.record_photos (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id),
  job_id uuid,
  estimate_id uuid,
  invoice_id uuid,
  file_name text not null check (length(file_name) between 1 and 240),
  byte_size integer not null check (byte_size between 1 and 10485760),
  media_type text not null check (media_type in ('image/jpeg','image/png','image/webp')),
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  storage_path text generated always as (business_id::text || '/' || id::text ||
    case media_type when 'image/jpeg' then '.jpg' when 'image/png' then '.png' else '.webp' end) stored unique,
  check (num_nonnulls(job_id,estimate_id,invoice_id)=1),
  foreign key (job_id,business_id) references public.jobs(id,business_id),
  foreign key (estimate_id,business_id) references public.estimates(id,business_id),
  foreign key (invoice_id,business_id) references public.invoices(id,business_id)
);
create index record_photos_job on public.record_photos(business_id,job_id) where job_id is not null;
create index record_photos_estimate on public.record_photos(business_id,estimate_id) where estimate_id is not null;
create index record_photos_invoice on public.record_photos(business_id,invoice_id) where invoice_id is not null;
alter table public.record_photos enable row level security;
revoke all on public.record_photos from public, anon, authenticated;
grant select,insert,delete on public.record_photos to authenticated;
grant all on public.record_photos to service_role;
create policy record_photos_read on public.record_photos for select to authenticated using (
  private.has_business_role(business_id, case when job_id is not null
    then array['owner','admin','office','technician','viewer'] else array['owner','admin','office'] end)
);
create policy record_photos_insert on public.record_photos for insert to authenticated with check (
  created_by=(select auth.uid()) and private.has_business_role(business_id,
    case when job_id is not null then array['owner','admin','office','technician'] else array['owner','admin','office'] end)
);
create policy record_photos_delete on public.record_photos for delete to authenticated using (
  private.has_business_role(business_id, array['owner','admin','office']) or
  (job_id is not null and created_by=(select auth.uid()) and private.has_business_role(business_id,array['technician']))
);

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('finviant-record-photos','finviant-record-photos',false,10485760,array['image/jpeg','image/png','image/webp']);
-- Metadata exists before upload. The path is generated by SQL, not user controlled.
create policy record_photo_objects_read on storage.objects for select to authenticated using (
  bucket_id='finviant-record-photos' and exists(select 1 from public.record_photos p where p.storage_path=name)
);
create policy record_photo_objects_insert on storage.objects for insert to authenticated with check (
  bucket_id='finviant-record-photos' and exists(select 1 from public.record_photos p where p.storage_path=name
    and p.created_by=(select auth.uid()) and private.has_business_role(p.business_id,
      case when p.job_id is not null then array['owner','admin','office','technician'] else array['owner','admin','office'] end))
);
create policy record_photo_objects_delete on storage.objects for delete to authenticated using (
  bucket_id='finviant-record-photos' and exists(select 1 from public.record_photos p where p.storage_path=name and (
    private.has_business_role(p.business_id,array['owner','admin','office']) or
    (p.job_id is not null and p.created_by=(select auth.uid()) and private.has_business_role(p.business_id,array['technician']))))
);
-- No UPDATE/overwrite permission: a new photo always has a new immutable UUID.

-- Use the existing ledger so costs appear once in Financial Performance.
alter table public.bookkeeping_entries
  add column job_id uuid,
  add column estimate_id uuid,
  add column invoice_id uuid,
  add constraint bookkeeping_record_one_target check (num_nonnulls(job_id,estimate_id,invoice_id)<=1),
  add constraint bookkeeping_record_expense_only check (num_nonnulls(job_id,estimate_id,invoice_id)=0 or direction='expense'),
  add constraint bookkeeping_job_tenant_fk foreign key (job_id,business_id) references public.jobs(id,business_id),
  add constraint bookkeeping_estimate_tenant_fk foreign key (estimate_id,business_id) references public.estimates(id,business_id),
  add constraint bookkeeping_invoice_tenant_fk foreign key (invoice_id,business_id) references public.invoices(id,business_id);
create index bookkeeping_job on public.bookkeeping_entries(business_id,job_id) where job_id is not null;
create index bookkeeping_estimate on public.bookkeeping_entries(business_id,estimate_id) where estimate_id is not null;
create index bookkeeping_invoice on public.bookkeeping_entries(business_id,invoice_id) where invoice_id is not null;
comment on table public.record_photos is 'Private photos for one job, estimate or invoice. Remove storage object before metadata. Financial document photos require finance access.';
